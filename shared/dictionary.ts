export interface DomainDef {
  id: string;
  label: string;
  /** Related GitHub topics, shown to explain the mapping (not used as qualifiers). */
  topics: string[];
  /** Default free-text term appended to the GitHub query. */
  term: string;
  /** Phrases that trigger this domain. */
  synonyms: string[];
  /**
   * Synonyms precise enough to be the search term themselves
   * (e.g. "kubernetes" beats the generic "devops").
   */
  specific?: string[];
}

